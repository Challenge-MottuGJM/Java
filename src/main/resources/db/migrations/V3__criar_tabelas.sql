CREATE TABLE GALPAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME_GALPAO VARCHAR2(255),
    PRIMARY KEY (ID)
);

CREATE TABLE ANDAR (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_ANDAR NUMBER,
    GALPAO_ID NUMBER NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE PATIO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_PATIO NUMBER,
    ANDAR_ID NUMBER NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE BLOCO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    LETRA_BLOCO VARCHAR2(255),
    PATIO_ID NUMBER NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE VAGA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_VAGA NUMBER,
    BLOCO_ID NUMBER NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE MOTO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STATUS VARCHAR2(255),
    MODELO VARCHAR2(255),
    MARCA VARCHAR2(255),
    PLACA VARCHAR2(255),
    CHASSI VARCHAR2(255),
    VAGA_ID NUMBER NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE USUARIO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(255),
    SENHA VARCHAR2(255),
    USERNAME VARCHAR2(255),
    CARGO VARCHAR2(255),
    PRIMARY KEY (ID)
);

CREATE TABLE CARGO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(255),
    PRIMARY KEY (ID)
);

CREATE TABLE USUARIO_CARGO (
    USUARIO_ID NUMBER NOT NULL,
    CARGO_ID NUMBER NOT NULL,
    PRIMARY KEY (USUARIO_ID, CARGO_ID)
);
